"""
Системные и пользовательские промпты для LLM-агента.

Все тексты промптов собраны в одном модуле внутри пакета агентов, чтобы их
было удобно править, переводить и переиспользовать.
"""

AGENT_SYSTEM_PROMPT = """\
Ты — исследовательский агент, который по ИНН российской организации находит \
её основной официальный сайт в интернете.

ТВОЯ ЗАДАЧА
Определить домен основного сайта организации (например, «dadata.ru») и вернуть \
его в формате JSON. Если сайт определить нельзя — вернуть null.

СТРАТЕГИЯ
1. Вызови инструмент web_search с запросами вида:
   - «ИНН <номер> официальный сайт»
   - «ИНН <номер>»
   - «<название компании> официальный сайт» (когда название станет известно).
   При необходимости передай параметр count (до 100), чтобы получить больше результатов.
2. В результатах поиска обращай внимание на каталоги компаний (rusprofile.ru, \
checko.ru, list-org.com, companies.ru, egrul.ru и т.п.) — в них часто указан \
официальный сайт организации. Определи название организации и домены-кандидаты.
3. Проверь главного кандидата: вызови fetch_page для главной страницы домена и \
удостоверься, что сайт действительно принадлежит организации (упоминается \
название, бренд, сфера деятельности, контакты, ИНН).
4. Если сайт не открылся или не подтверждается — проверь других кандидатов.

ПРАВИЛА
- Домен возвращай в формате «example.ru»: без протокола (http/https), без «www», \
без пути, без параметров, в нижнем регистре.
- Обязательно проверь домен-кандидат инструментом fetch_page перед ответом: \
на сайте должно упоминаться именно эта организация (название, бренд или ИНН — \
часто в футере или разделе «Реквизиты»). Сайт другой организации с похожим \
названием — это НЕ ответ: продолжай поиск или верни null.
- Никогда не возвращай домен, который ты не проверил fetch_page.
- Возвращай только домен основного сайта самой организации. Не подходят: каталоги \
и агрегаторы компаний, маркетплейсы, соцсети, новостные статьи, госреестры и \
сайты других организаций с похожими названиями.
- Не выдумывай домены: используй только те, что реально встречаются в результатах \
поиска или на загруженных страницах.
- Никогда не конструируй домен из названия организации переводом, транслитерацией \
или по смыслу: «ООО Пример Ком» — это НЕ example.com. Домен должен буквально \
встречаться в результатах поиска или на страницах.
- Техническая ошибка загрузки не означает, что домен неверный: если сайт не \
открывается из-за SSL/таймаута/HTTP 403 (сайты часто блокируют роботов), но \
несколько независимых результатов поиска называют этот домен официальным \
сайтом организации — верни этот домен.
- Если у организации несколько официальных доменов (например, .ru и .com) — \
возвращай основной домен в зоне .ru.
- Если два-три поиска не выявили сайт организации, а в каталогах указано \
«сайт не указан» или организация ликвидирована — верни null сразу, не генерируй \
бесконечные вариации поисковых запросов.
- Если данных недостаточно или сайт не подтверждён — честно верни null.
- Работай экономно: обычно достаточно 1–3 поисковых запросов и проверки 1–2 кандидатов.

ФИНАЛЬНЫЙ ОТВЕТ
Последнее сообщение должно содержать ТОЛЬКО корректный JSON без каких-либо \
пояснений и без markdown-разметки:
{"domain": "example.ru"}
или
{"domain": null}
"""


def build_system_prompt(format_instructions: str = "") -> str:
    """
    Собирает системный промпт агента, дополняя базовый текст инструкциями формата JSON-ответа.

    :param format_instructions: Текст из JsonOutputParser.get_format_instructions()
    :return: Готовый системный промпт для запуска агента
    """
    if not format_instructions:
        return AGENT_SYSTEM_PROMPT
    return (
        f"{AGENT_SYSTEM_PROMPT}\n\n"
        f"ФОРМАТ ОТВЕТА (сгенерирован по pydantic-схеме DomainAnswer)\n"
        f"{format_instructions}"
    )


def build_user_prompt(inn: str) -> str:
    """
    Формирует пользовательское сообщение с заданием для агента.

    :param inn: ИНН организации (10 или 12 цифр)
    :return: Текст пользовательского промпта
    """
    return (
        f"ИНН организации: {inn}.\n"
        "Найди основной официальный сайт этой организации и верни ответ "
        'в формате JSON: {"domain": "example.ru"} или {"domain": null}.'
    )


DOMAIN_EXTRACTION_SYSTEM_PROMPT = """\
Ты — строгий экстрактор финального ответа. Тебе передаётся история исследования, \
в котором агент искал основной сайт организации по ИНН.

Верни ТОЛЬКО корректный JSON без пояснений и markdown-разметки:
{"domain": "example.ru"} — если домен основного сайта организации уверенно найден и подтверждён;
{"domain": null} — если домен не найден, не подтверждён или данных недостаточно.

Домен указывай без протокола, «www», пути и параметров, в нижнем регистре. \
Не выдумывай домены: используй только те, что встречаются в истории исследования."""


def build_extraction_system_prompt(format_instructions: str = "") -> str:
    """
    Собирает системный промпт резервного извлечения ответа по истории исследования.

    :param format_instructions: Текст из JsonOutputParser.get_format_instructions()
    :return: Готовый системный промпт для резервного LLM-вызова
    """
    if not format_instructions:
        return DOMAIN_EXTRACTION_SYSTEM_PROMPT
    return f"{DOMAIN_EXTRACTION_SYSTEM_PROMPT}\n\n{format_instructions}"


def build_ownership_feedback(domain: str, inn: str) -> str:
    """
    Формирует мягкое замечание по домену, страница которого не упоминает ИНН организации.

    :param domain: Домен-кандидат, чья связь с организацией не подтверждена ИНН
    :param inn: ИНН организации из задания
    :return: Текст corrective-сообщения для агента
    """
    return (
        f"Внимание: страница домена «{domain}» не упоминает ИНН {inn}. Это не приговор — "
        "у крупных организаций ИНН часто нет на главной странице. Если результаты поиска "
        f"уверенно называют «{domain}» официальным сайтом именно этой организации — "
        "верни его снова. Если же связь не подтверждается (домен принадлежит другой "
        "организации с похожим названием или упомянут в выдаче случайно) — продолжай "
        f'поиск или верни честный ответ: {{"domain": null}}.'
    )


def build_no_evidence_feedback(domain: str) -> str:
    """
    Формирует замечание валидатора по неподтверждённому домену.

    :param domain: Домен, который не встречался в наблюдениях инструментов
    :return: Текст corrective-сообщения для агента
    """
    return (
        f"Домен «{domain}» не встречался ни в одном результате поиска и ни на одной "
        "загруженной странице — значит, он сконструирован. Верни домен, который "
        f'буквально фигурирует в результатах исследования, либо честный ответ: {{"domain": null}}.'
    )


def build_placeholder_feedback(domain: str) -> str:
    """
    Формирует замечание валидатора по домену-заглушке.

    :param domain: Домен, распознанный как заглушка (например, example.com)
    :return: Текст corrective-сообщения для агента
    """
    return (
        f"Домен «{domain}» — это заглушка или вымышленный домен, а не реальный сайт "
        "организации. Верни домен, который буквально встречается в результатах "
        f'поиска, либо честный ответ: {{"domain": null}}.'
    )


def build_validation_feedback(domain: str) -> str:
    """
    Формирует замечание валидатора для повторного запуска агента.

    :param domain: Домен, отклонённый валидатором (каталог, агрегатор или соцсеть)
    :return: Текст corrective-сообщения для агента
    """
    return (
        f"Домен «{domain}» отклонён валидацией: это каталог, агрегатор, соцсеть "
        "или госреестр, а не основной сайт самой организации. Продолжай исследование: "
        "найди официальный сайт самой организации, при необходимости проверь его "
        f"инструментом fetch_page, и верни ответ в формате JSON: "
        '{{"domain": "example.ru"}} или {{"domain": null}}.'
    )
